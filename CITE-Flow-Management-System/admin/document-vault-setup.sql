DROP POLICY IF EXISTS "Public can view documents storage" ON storage.objects;
DROP POLICY IF EXISTS "Public can insert documents storage" ON storage.objects;
DROP POLICY IF EXISTS "Public can update documents storage" ON storage.objects;
DROP POLICY IF EXISTS "Public can delete documents storage" ON storage.objects;
DROP POLICY IF EXISTS "Allow public delete documents bucket" ON storage.objects;
DROP POLICY IF EXISTS "Allow public read documents bucket" ON storage.objects;
DROP POLICY IF EXISTS "Allow public update documents bucket" ON storage.objects;
DROP POLICY IF EXISTS "Allow public upload documents bucket" ON storage.objects;

-- Step B: Drop both function overloads to fix "ERROR: 42725: function is_document_vault_admin() is not unique"
DROP FUNCTION IF EXISTS public.is_document_vault_admin() CASCADE;
DROP FUNCTION IF EXISTS public.is_document_vault_admin(uuid) CASCADE;

-- Step C: Create a single unambiguous 0-argument helper function
CREATE OR REPLACE FUNCTION public.is_document_vault_admin()
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    target_uid uuid;
    target_email text;
BEGIN
    target_uid := auth.uid();
    IF target_uid IS NULL THEN
        RETURN false;
    END IF;

    -- Look up email from auth.users (SECURITY DEFINER allows reading auth.users)
    SELECT lower(trim(email)) INTO target_email
    FROM auth.users
    WHERE id = target_uid;

    -- 1. Checked against admin_profiles table (by id or email)
    IF EXISTS (
        SELECT 1
        FROM public.admin_profiles ap
        WHERE (ap.id::text = target_uid::text
           OR (target_email IS NOT NULL AND lower(trim(coalesce(ap.email, ''))) = target_email))
          AND lower(coalesce(ap.role, 'administrator')) NOT LIKE '%chair%'
    ) THEN
        RETURN true;
    END IF;

    -- 2. Checked against faculty table with admin role, position, or admin_access flag
    IF EXISTS (
        SELECT 1
        FROM public.faculty f
        WHERE (f.auth_user_id::text = target_uid::text
           OR (target_email IS NOT NULL AND lower(trim(coalesce(f.email, f.existing_email, ''))) = target_email))
          AND (
            lower(coalesce(f.role, f.position, '')) LIKE '%admin%'
            OR lower(coalesce(f.role, f.position, '')) IN ('dean', 'secretary', 'college secretary', 'college_secretary', 'superadmin', 'director')
            OR coalesce(f.admin_access, false) = true
          )
          AND (
            lower(coalesce(f.role, f.position, '')) NOT LIKE '%chair%'
            OR coalesce(f.admin_access, false) = true
          )
    ) THEN
        RETURN true;
    END IF;

    -- 3. Checked against auth.users metadata (raw_user_meta_data & raw_app_meta_data)
    IF EXISTS (
        SELECT 1
        FROM auth.users u
        WHERE u.id = target_uid
          AND (
            lower(coalesce(u.raw_user_meta_data ->> 'role', '')) LIKE '%admin%'
            OR lower(coalesce(u.raw_user_meta_data ->> 'role', '')) IN ('dean', 'secretary', 'college secretary', 'superadmin', 'director')
            OR lower(coalesce(u.raw_app_meta_data ->> 'role', '')) LIKE '%admin%'
            OR lower(coalesce(u.raw_app_meta_data ->> 'role', '')) IN ('dean', 'secretary', 'college secretary', 'superadmin', 'director')
          )
          AND position('chair' in lower(coalesce(u.raw_user_meta_data ->> 'role', ''))) = 0
    ) THEN
        RETURN true;
    END IF;

    -- 4. Shared CITE-Flow wf_is_final_approver() if defined and caller is the session user
    IF to_regprocedure('public.wf_is_final_approver()') IS NOT NULL THEN
        IF public.wf_is_final_approver() THEN
            RETURN true;
        END IF;
    END IF;

    RETURN false;
END;
$$;

GRANT EXECUTE ON FUNCTION public.is_document_vault_admin() TO authenticated, anon;

-- Step D: Ensure authenticated users can query bucket metadata for 'documents'
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE schemaname = 'storage' AND tablename = 'buckets' AND policyname = 'authenticated_read_documents_bucket'
    ) THEN
        CREATE POLICY "authenticated_read_documents_bucket" ON storage.buckets
            FOR SELECT TO authenticated
            USING (id = 'documents' OR public = true);
    END IF;
END $$;

-- Step E: Clean and strictly scoped policies for 'documents' bucket only

-- Policy 1: List and view/download documents from 'documents' bucket
CREATE POLICY "documents_storage_select_admin" ON storage.objects
    FOR SELECT TO authenticated
    USING (
        bucket_id = 'documents'
        AND public.is_document_vault_admin()
    );

-- Policy 2: Upload new files to 'documents' bucket
CREATE POLICY "documents_storage_insert_admin" ON storage.objects
    FOR INSERT TO authenticated
    WITH CHECK (
        bucket_id = 'documents'
        AND public.is_document_vault_admin()
    );

-- Policy 3: Update existing files in 'documents' bucket (required for upsert: true)
CREATE POLICY "documents_storage_update_admin" ON storage.objects
    FOR UPDATE TO authenticated
    USING (
        bucket_id = 'documents'
        AND public.is_document_vault_admin()
    )
    WITH CHECK (
        bucket_id = 'documents'
        AND public.is_document_vault_admin()
    );

-- Policy 4: Delete files from 'documents' bucket
CREATE POLICY "documents_storage_delete_admin" ON storage.objects
    FOR DELETE TO authenticated
    USING (
        bucket_id = 'documents'
        AND public.is_document_vault_admin()
    );

