-- 1. Create folders table if not exists
CREATE TABLE IF NOT EXISTS public.folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    icon TEXT DEFAULT 'fa-folder',
    color TEXT DEFAULT '#6b21a8',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Create documents table if not exists
CREATE TABLE IF NOT EXISTS public.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    folder_id BIGINT REFERENCES public.folders(id) ON DELETE CASCADE,
    file_path TEXT NOT NULL,
    mime_type TEXT,
    size_bytes BIGINT,
    uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    uploaded_by TEXT
);

-- 3. Enable RLS on database tables
ALTER TABLE public.folders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.documents ENABLE ROW LEVEL SECURITY;

-- 4. Set RLS Policies for folders (anon and authenticated)
DROP POLICY IF EXISTS "Allow all for folders" ON public.folders;
DROP POLICY IF EXISTS "Allow all for authenticated users - folders" ON public.folders;
CREATE POLICY "Allow all for folders" ON public.folders
    FOR ALL TO public, anon, authenticated
    USING (true)
    WITH CHECK (true);

-- 5. Set RLS Policies for documents (anon and authenticated)
DROP POLICY IF EXISTS "Allow all for documents" ON public.documents;
DROP POLICY IF EXISTS "Allow all for authenticated users - documents" ON public.documents;
CREATE POLICY "Allow all for documents" ON public.documents
    FOR ALL TO public, anon, authenticated
    USING (true)
    WITH CHECK (true);

-- 6. Create indexes for high performance
CREATE INDEX IF NOT EXISTS idx_documents_folder_id ON public.documents(folder_id);
CREATE INDEX IF NOT EXISTS idx_documents_uploaded_at ON public.documents(uploaded_at DESC);
CREATE INDEX IF NOT EXISTS idx_folders_name ON public.folders(name);

-- 7. Initialize Storage Bucket 'documents' as PRIVATE
UPDATE storage.buckets SET public = false WHERE id = 'documents';
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES ('documents', 'documents', false, NULL, NULL)
ON CONFLICT (id) DO UPDATE SET 
    name = 'documents',
    public = false;

-- 8. Storage Object Policies for 'documents' bucket
-- Exclusively restricted to bucket_id = 'documents' and TO authenticated (Admins)
-- Does NOT touch any other bucket (e.g. wf-submissions, faculty-accomplishments, etc.)

-- Step A: Drop old storage policies FIRST so they don't block dropping old functions
DROP POLICY IF EXISTS "documents_storage_select_admin" ON storage.objects;
DROP POLICY IF EXISTS "documents_storage_insert_admin" ON storage.objects;
DROP POLICY IF EXISTS "documents_storage_update_admin" ON storage.objects;
DROP POLICY IF EXISTS "documents_storage_delete_admin" ON storage.objects;
